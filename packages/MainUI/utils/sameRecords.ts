import type { EntityData } from "@workspaceui/api-client/src/api/types";

/** Same record when it is the same object or every top-level value is identical (nested values by reference). */
export const sameRecord = (a?: EntityData, b?: EntityData): boolean => {
  if (a === b) return true;
  if (!a || !b) return false;
  const keys = Object.keys(a);
  if (keys.length !== Object.keys(b).length) return false;
  return keys.every((key) => Object.is(a[key], b[key]));
};

/** Same list when it has the same records in the same order. */
export const sameRecords = (a: EntityData[], b: EntityData[]): boolean =>
  a === b || (a.length === b.length && a.every((record, index) => sameRecord(record, b[index])));
