/**
 * Formats the calendar day of a Date as yyyy-MM-dd using its local year, month and day.
 *
 * Use it instead of `date.toISOString().split("T")[0]` for a day the user typed or picked: a Date built at
 * local midnight is the previous day in UTC for every timezone east of it, so the ISO string shifts the day.
 */
export function formatLocalIsoDate(date: Date): string {
  const year = String(date.getFullYear()).padStart(4, "0");
  const month = String(date.getMonth() + 1).padStart(2, "0");
  const day = String(date.getDate()).padStart(2, "0");
  return `${year}-${month}-${day}`;
}
